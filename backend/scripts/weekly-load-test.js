#!/usr/bin/env node

const fs = require("node:fs");
const path = require("node:path");
const { promisify } = require("node:util");
const autocannon = require("autocannon");

const runAutocannon = promisify(autocannon);

const MAINTAINER = "GB5IWBA6RTXMZSCMHFSVNL6IIZMHH5WJOH7JXZ2UTZD3VP2WBVWJJOOK";

function printHelp() {
  console.log(`Weekly backend load test

Environment variables:
  BASE_URL                         Backend URL (default: http://127.0.0.1:3001)
  LOAD_TEST_CONNECTIONS            Autocannon connections (default: 20)
  LOAD_TEST_DURATION_SECONDS       Duration per scenario (default: 30)
  LOAD_TEST_SEED_BOUNTIES          Bounties to seed before running (default: 20)
  LOAD_TEST_MAX_P99_MS             Maximum allowed p99 latency (default: 500)
  LOAD_TEST_MAX_ERROR_RATE         Maximum allowed error rate percent (default: 1)
  LOAD_TEST_SUMMARY_PATH           Markdown summary path (default: ./load-test-summary.md)
`);
}

function intFromEnv(name, fallback) {
  const raw = process.env[name];
  if (!raw) {
    return fallback;
  }
  const parsed = Number(raw);
  if (!Number.isInteger(parsed) || parsed <= 0) {
    throw new Error(`${name} must be a positive integer.`);
  }
  return parsed;
}

function numberFromEnv(name, fallback) {
  const raw = process.env[name];
  if (!raw) {
    return fallback;
  }
  const parsed = Number(raw);
  if (!Number.isFinite(parsed) || parsed < 0) {
    throw new Error(`${name} must be a non-negative number.`);
  }
  return parsed;
}

function makeBountyPayload(sequence) {
  return {
    repo: "ritik4ever/stellar-bounty-board",
    issueNumber: 100000 + sequence,
    title: `Weekly load test bounty ${sequence}`,
    summary: "Synthetic bounty generated by the weekly backend load test workflow.",
    maintainer: MAINTAINER,
    tokenSymbol: "XLM",
    amount: 10,
    deadlineDays: 30,
    labels: ["load-test"],
  };
}

async function createBounty(baseUrl, sequence) {
  const response = await fetch(`${baseUrl}/api/bounties`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify(makeBountyPayload(sequence)),
  });

  if (!response.ok) {
    const body = await response.text();
    throw new Error(`Seed request failed with ${response.status}: ${body}`);
  }
}

async function seedBounties(baseUrl, count) {
  for (let i = 1; i <= count; i += 1) {
    await createBounty(baseUrl, i);
  }
}

function summarizeResult(name, result, maxP99Ms, maxErrorRate) {
  const requests = result.requests?.total ?? 0;
  const errors = result.errors ?? 0;
  const timeouts = result.timeouts ?? 0;
  const non2xx = result.non2xx ?? 0;
  const p99 = result.latency?.p99 ?? 0;
  const failedRequests = errors + timeouts + non2xx;
  const errorRate = requests > 0 ? (failedRequests / requests) * 100 : 100;

  return {
    name,
    requests,
    p99,
    errors,
    timeouts,
    non2xx,
    errorRate,
    passed: p99 <= maxP99Ms && errorRate <= maxErrorRate,
  };
}

function markdownTable(summaries, maxP99Ms, maxErrorRate) {
  const lines = [
    "# Weekly Backend Load Test",
    "",
    `Thresholds: p99 <= ${maxP99Ms}ms, error rate <= ${maxErrorRate}%`,
    "",
    "| Scenario | Requests | p99 latency | Errors | Timeouts | Non-2xx | Error rate | Result |",
    "| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
  ];

  for (const summary of summaries) {
    lines.push(
      `| ${summary.name} | ${summary.requests} | ${summary.p99.toFixed(2)}ms | ` +
        `${summary.errors} | ${summary.timeouts} | ${summary.non2xx} | ` +
        `${summary.errorRate.toFixed(2)}% | ${summary.passed ? "PASS" : "FAIL"} |`,
    );
  }

  return `${lines.join("\n")}\n`;
}

async function runScenario({ name, baseUrl, path, method, connections, duration }) {
  let sequence = 0;

  return runAutocannon({
    url: baseUrl,
    connections,
    duration,
    requests: [
      {
        method,
        path,
        headers: method === "POST" ? { "content-type": "application/json" } : undefined,
        setupRequest: (request) => {
          if (method === "POST") {
            sequence += 1;
            request.body = JSON.stringify(makeBountyPayload(200000 + sequence));
          }
          return request;
        },
      },
    ],
  }).then((result) => ({ name, result }));
}

async function main() {
  if (process.argv.includes("--help") || process.argv.includes("-h")) {
    printHelp();
    return;
  }

  const baseUrl = process.env.BASE_URL ?? "http://127.0.0.1:3001";
  const connections = intFromEnv("LOAD_TEST_CONNECTIONS", 20);
  const duration = intFromEnv("LOAD_TEST_DURATION_SECONDS", 30);
  const seedCount = intFromEnv("LOAD_TEST_SEED_BOUNTIES", 20);
  const maxP99Ms = numberFromEnv("LOAD_TEST_MAX_P99_MS", 500);
  const maxErrorRate = numberFromEnv("LOAD_TEST_MAX_ERROR_RATE", 1);
  const summaryPath = process.env.LOAD_TEST_SUMMARY_PATH
    ? path.resolve(process.env.LOAD_TEST_SUMMARY_PATH)
    : path.resolve(process.cwd(), "load-test-summary.md");

  await seedBounties(baseUrl, seedCount);

  const scenarios = [
    await runScenario({
      name: "GET /api/bounties",
      baseUrl,
      path: "/api/bounties",
      method: "GET",
      connections,
      duration,
    }),
    await runScenario({
      name: "POST /api/bounties",
      baseUrl,
      path: "/api/bounties",
      method: "POST",
      connections,
      duration,
    }),
  ];

  const summaries = scenarios.map((scenario) =>
    summarizeResult(scenario.name, scenario.result, maxP99Ms, maxErrorRate),
  );
  const markdown = markdownTable(summaries, maxP99Ms, maxErrorRate);

  fs.writeFileSync(summaryPath, markdown);
  if (process.env.GITHUB_STEP_SUMMARY) {
    fs.appendFileSync(process.env.GITHUB_STEP_SUMMARY, markdown);
  }
  process.stdout.write(markdown);

  if (summaries.some((summary) => !summary.passed)) {
    process.exitCode = 1;
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
